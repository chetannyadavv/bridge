def _seed_demo_scenario(db, *, dispute_id, txn_id, merchant_name, reason, amount, created, evidence):
    """Creates one demo dispute with the given evidence already submitted,
    and computes its recommendation via the real engine — used for the
    four Sprint 6 demo scenarios (Approve / Reject / Request Additional
    Evidence / Escalate)."""
    db.add(Transaction(id=txn_id, merchant_name=merchant_name, amount=amount, currency="USD", occurred_at=created))
    dispute = Dispute(
        id=dispute_id,
        transaction_id=txn_id,
        customer_name="Priya Nair",
        merchant_name=merchant_name,
        reason=reason,
        reason_code=infer_reason_code(reason),
        amount=amount,
        currency="USD",
        status=DisputeStatus.OPEN if not evidence else DisputeStatus.IN_NEGOTIATION,
        created_at=created,
    )
    db.add(dispute)
    db.add(
        TimelineEvent(
            id=_uid("evt"), dispute_id=dispute_id, timestamp=created,
            title="Dispute Created", description=f"Cardholder opened a dispute: {reason}.",
        )
    )

    evidence_items = []
    for uploader, etype, credibility, summary in evidence:
        item = _evidence(dispute_id, uploader, etype, credibility, summary, created)
        db.add(item)
        evidence_items.append(item)
        db.add(
            TimelineEvent(
                id=_uid("evt"), dispute_id=dispute_id, timestamp=created,
                title="Merchant Response Added" if uploader == UploaderRole.merchant else "Evidence Uploaded",
                description=summary,
            )
        )

    _snapshot_recommendation(db, dispute, evidence_items, None, created)
