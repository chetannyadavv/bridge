# Fixed id — the frontend's Landing page links directly to
# /disputes/dsp_8841 ("View a live workspace"), so this id must stay
# stable across restarts for that link to keep working.
SEED_DISPUTE_ID = "dsp_8841"


def _uid(prefix: str) -> str:
    return f"{prefix}_{uuid.uuid4().hex[:10]}"


def _evidence(dispute_id, uploader, etype, credibility, summary, ts):
    return Evidence(
        id=_uid("ev"),
        dispute_id=dispute_id,
        uploader=uploader,
        type=etype,
        credibility=credibility,
        summary=summary,
        created_at=ts,
    )


def _snapshot_recommendation(db, dispute, evidence_so_far, previous, updated_at):
    """
    Sprint 6: seed data is generated by calling the SAME
    compute_recommendation() the live app uses at evidence-submission
    time, rather than hand-written recommendation text. This was a real
    inconsistency worth fixing — the original dsp_8841 seed copy
    (written in Sprint 1, before the Decision Engine existed) had never
    been regenerated and no longer matched what the real engine would
    actually produce for that evidence once Sprint 5 landed.
    """
    rec = compute_recommendation(dispute, evidence_so_far, previous)
    rec.updated_at = updated_at  # override server_default for narrative pacing
    db.add(rec)
    return rec


